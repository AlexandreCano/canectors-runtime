def datafield_cases() -> list[Case]:
    shapes: list[tuple[str, str, str | None, str]] = [
        # (label, source path, dataField (None = omit), expected record id)
        ("explicit-data", "/source/matrix/record", "data", "MTX-1"),
        ("implicit-data", "/source/matrix/record", None, "MTX-1"),
        ("implicit-items", "/source/matrix/items", None, "SHAPE-items"),
        ("implicit-results", "/source/matrix/results", None, "SHAPE-results"),
        ("implicit-records", "/source/matrix/records", None, "SHAPE-records"),
        ("explicit-items", "/source/matrix/items", "items", "SHAPE-items"),
        ("root-array-no-datafield", "/source/matrix/root-array", None, "ROOT-1"),
        ("nested-datafield-path", "/source/matrix/deep", "payload.inner.rows", "DEEP-1"),
    ]
    cases: list[Case] = []
    for label, path, data_field, expected_id in shapes:
        override: dict = {"endpoint": f"http://localhost:18080{path}"}
        if data_field is None:
            override["dataField"] = None
        else:
            override["dataField"] = data_field
        cases.append(
            Case(
                name=f"datafield-{label}",
                description=f"input response shape: {label}.",
                filters=[],
                body_contains=[field_is("id", expected_id)],
                input_override=override,
                axis="datafield",
            )
        )
    return cases


