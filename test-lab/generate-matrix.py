#!/usr/bin/env python3
"""Generate combinatorial test-lab scenarios from a declarative matrix.

Hand-writing hundreds of near-identical scenarios does not scale and rots fast,
so the deep combinatorial layer is generated instead. Every cell of the matrix
below pairs an input value with the behaviour the runtime is specified to
produce, so a generated assertion failing means a real defect — these are not
snapshots of current behaviour.

Generated files carry a `gen-` prefix and a "generated" header. They are safe to
delete and regenerate:

    test-lab/generate-matrix.py            # write pipelines + scenarios
    test-lab/generate-matrix.py --clean    # remove generated files only
    test-lab/generate-matrix.py --list     # print what would be generated

Expected values are JSON-encoded the way Go's encoding/json renders them, so the
scenarios can assert on a `"target":value` substring of the batched request body.
"""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

LAB = Path(__file__).resolve().parent
PIPELINES = LAB / "pipelines"
SCENARIOS = LAB / "scenarios"
PREFIX = "gen-"

SOURCE = "http://localhost:18080/source/matrix/record"
SINK = "http://localhost:18080/destination/matrix/sink"
SINK_PATH = "/destination/matrix/sink"

HEADER = "# GENERATED by test-lab/generate-matrix.py — do not edit by hand.\n"


@dataclass
class Case:
    """One matrix cell: a pipeline plus the assertions it must satisfy."""

    name: str
    description: str
    filters: list[dict]
    # Substrings expected in the request body reaching the sink.
    body_contains: list[str] = field(default_factory=list)
    # Substrings that must NOT appear anywhere in the sink body.
    body_absent: list[str] = field(default_factory=list)
    expect_status: str = "success"
    log_contains: list[str] = field(default_factory=list)
    axis: str = "misc"
    # Merged into the generated input/output blocks, for cells that need a
    # different source, pagination config, method, requestMode or success block.
    input_override: dict = field(default_factory=dict)
    output_override: dict = field(default_factory=dict)
    # Assertions that do not target the default sink body.
    extra_assertions: list[dict] = field(default_factory=list)
    # Set when the cell asserts nothing on the default sink path.
    skip_sink_assertions: bool = False


def go_json(value: object) -> str:
    """Render a value the way Go's encoding/json would, for substring matching."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value.is_integer():
        # Go prints float64(1) as 1, not 1.0
        return str(int(value))
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def field_is(target: str, value: object) -> str:
    """The `"target":value` substring proving the field carries value."""
    return f'"{target}":{go_json(value)}'


