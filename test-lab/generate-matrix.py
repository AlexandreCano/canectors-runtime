    for label, path, retry, expected_calls in combos:
        cases.append(
            Case(
                name=f"retry-{label}",
                description=(
                    f"retry {retry} against {path} must issue exactly {expected_calls} request(s)."
                ),
                filters=[],
                skip_sink_assertions=True,
                expect_status="error",
                output_override={
                    "endpoint": f"http://localhost:18080{path}",
                    "retry": retry,
                },
                extra_assertions=[
                    {"http_count_eq": {"method": "POST", "path": path, "expected": expected_calls}}
                ],
                axis="retry",
            )
        )
    return cases


