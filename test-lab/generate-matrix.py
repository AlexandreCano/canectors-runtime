def render_pipeline(case: Case) -> str:
    input_block = {
        "type": "httpPolling",
        "schedule": "* * * * * *",
        "endpoint": SOURCE,
        "dataField": "data",
    }
    input_block.update(case.input_override)
    # An override of None means "omit this key" (used to test dataField fallback).
    input_block = {k: v for k, v in input_block.items() if v is not None}
    output_block = {
        "type": "httpRequest",
        "endpoint": SINK,
        "method": "POST",
        "headers": {"Content-Type": "application/json"},
    }
    output_block.update(case.output_override)
    doc = {
        "name": PREFIX + case.name,
        "version": "1.0.0",
        "description": case.description,
        "tags": ["test-lab", "generated", case.axis],
        "input": input_block,
        "filters": case.filters,
        "output": output_block,
    }
    return HEADER + json.dumps(doc, indent=2) + "\n"


def render_scenario(case: Case) -> str:
    assertions: list[dict] = []
    if case.skip_sink_assertions and (case.body_contains or case.body_absent):
        raise SystemExit(f"{case.name}: skip_sink_assertions set but body assertions given")
    for needle in case.body_contains:
        assertions.append(
            {
                "http_count_ge": {
                    "method": "POST",
                    "path": SINK_PATH,
                    "body_contains": needle,
                    "expected": 1,
                }
            }
        )
    for needle in case.body_absent:
        assertions.append(
            {
                "http_count_eq_zero": {
                    "method": "POST",
                    "path": SINK_PATH,
                    "body_contains": needle,
                }
            }
        )
    assertions.extend(case.extra_assertions)
    for needle in case.log_contains:
        assertions.append({"log_contains": needle})
    assertions.append({"log_not_contains": "panic:"})

    doc = {
        "name": PREFIX + case.name,
        "description": case.description,
        "pipeline": f"test-lab/pipelines/{PREFIX}{case.name}.yaml",
        "expect_status": case.expect_status,
        # These cells never touch the database, so skip that reset to keep the
        # generated layer fast. The mapping reload stays on: without it a stub
        # added since the lab booted would 404 and look like a runtime bug.
        "setup": {"reset_db": False},
        "assertions": assertions,
    }
    return HEADER + json.dumps(doc, indent=2) + "\n"


def all_cases() -> list[Case]:
    cases = (
        transform_cases()
        + on_missing_cases()
        + set_remove_cases()
        + condition_cases()
        + script_cases()
        + loop_cases()
        + drop_cases()
        + template_cases()
        + success_cases()
        + method_cases()
        + pagination_edge_cases()
        + on_error_cases()
        + transform_chain_cases()
        + template_header_cases()
        + condition_extra_cases()
        + retry_matrix_cases()
        + datafield_cases()
    )
    seen: set[str] = set()
    for case in cases:
        if case.name in seen:
            raise SystemExit(f"duplicate generated case name: {case.name}")
        seen.add(case.name)
    return cases


def clean() -> int:
    removed = 0
    for directory in (PIPELINES, SCENARIOS):
        for path in sorted(directory.glob(f"{PREFIX}*.yaml")):
            path.unlink()
            removed += 1
    return removed


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clean", action="store_true", help="remove generated files and exit")
    parser.add_argument("--list", action="store_true", help="list generated case names and exit")
    args = parser.parse_args(argv[1:])

    if args.clean:
        print(f"removed {clean()} generated file(s)")
        return 0

    cases = all_cases()
    if args.list:
        by_axis: dict[str, int] = {}
        for case in cases:
            by_axis[case.axis] = by_axis.get(case.axis, 0) + 1
            print(f"{case.axis:12} {PREFIX}{case.name}")
        print("\ntotals:")
        for axis, count in sorted(by_axis.items()):
            print(f"  {axis:12} {count}")
        print(f"  {'TOTAL':12} {len(cases)}")
        return 0

    clean()
    for case in cases:
        (PIPELINES / f"{PREFIX}{case.name}.yaml").write_text(render_pipeline(case))
        (SCENARIOS / f"{PREFIX}{case.name}.yaml").write_text(render_scenario(case))
    print(f"generated {len(cases)} pipeline/scenario pair(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
